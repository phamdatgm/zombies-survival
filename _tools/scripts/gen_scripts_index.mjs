// Regenerate web/src/game/scripts/index.js importing every ported script (stubs first).
import fs from 'node:fs';
import path from 'node:path';
const dir = process.argv[2] || 'web/src/game/scripts';
const files = fs.readdirSync(dir).filter((f) => f.endsWith('.js') && f !== 'index.js').sort((a, b) => (a === '_stubs.js' ? -1 : b === '_stubs.js' ? 1 : a.localeCompare(b)));
const out = '// Auto-generated by _tools/scripts/gen_scripts_index.mjs\n' + files.map((f) => `import './${f}';`).join('\n') + '\n';
fs.writeFileSync(path.join(dir, 'index.js'), out);
console.log(files.length, 'scripts');
